import {existsSync,readFileSync,renameSync,rmSync,writeFileSync} from "node:fs";
import {builtinModules,createRequire} from "node:module";
import path from "node:path";
import {fileURLToPath,pathToFileURL} from "node:url";

// The desktop backend used to load ~880 separate module files at every start (kysely alone is 254).
// Resolving and opening them cost ~2.5 s on a warm start and far more on a cold first launch, while
// running the code itself took milliseconds. This step bundles the compiled entry and its pure
// JavaScript dependencies into the same entry file that desktop/main.cjs already starts.
//  - It runs AFTER runtime-dependencies.mjs, so bundled packages come from the reviewed runtime set in
//    the payload, never from the developer's node_modules.
//  - Packages that read their own files or load native code at run time stay as separate files.
//  - Each bundled module's import.meta.url is rewritten to that module's ORIGINAL location (relative to
//    the bundle), so its .ps1 helpers, SQL migrations, password lists and createRequire() still resolve
//    exactly as before. Any other import.meta use stops the build instead of misbehaving at run time.
//  - All individual compiled files stay in place; only the entry file is replaced by the bundle.
const project=path.resolve(fileURLToPath(new URL("..",import.meta.url))),web=path.join(project,"web");
const builtins=new Set([...builtinModules,...builtinModules.map(m=>"node:"+m)]);
const external=/^(?:next|react|react-dom|better-sqlite3|styled-jsx|@next\/[^/]+|sharp)(?:\/.*)?$/;
export const BUNDLED_ENTRY="server/desktop/test-entry.js";

export async function bundleBackend(payload){
 payload=path.resolve(payload);
 const entry=path.join(payload,BUNDLED_ENTRY),outDir=path.dirname(entry),temporary=path.join(outDir,".bundle-tmp");
 if(!existsSync(entry)||!existsSync(path.join(payload,"node_modules"))||existsSync(temporary))throw Error("Compiled backend entry and reviewed runtime dependencies are required first.");
 if(readFileSync(entry,"utf8").startsWith("// SHOP_POS_BACKEND_BUNDLE_V1"))throw Error("Backend is already bundled; build a new payload.");
 const require=createRequire(path.join(web,"package.json"));
 const {rolldown}=await import(pathToFileURL(require.resolve("rolldown")).href);
 const inside=id=>{const r=path.relative(payload,id);return !!r&&!r.startsWith("..")&&!path.isAbsolute(r);};
 const bundled=new Set();
 const bundle=await rolldown({
  input:entry,platform:"node",logLevel:"warn",
  external:id=>builtins.has(id)||external.test(id),
  plugins:[{name:"shop-pos-original-module-url",
   transform(code,id){
    if(id.startsWith("\0"))return null; // the bundler's own small virtual runtime helpers
    const file=id.split("?")[0];
    if(!inside(file))throw Error("Bundled module outside the payload: "+file);
    bundled.add(path.relative(payload,file).split(path.sep).join("/"));
    if(!/\bimport\.meta\b/.test(code))return null;
    const relative=path.relative(outDir,file).split(path.sep).join("/"),spec=relative.startsWith(".")?relative:"./"+relative;
    const rewritten=code.replace(/\bimport\.meta\.url\b/g,"new URL("+JSON.stringify(spec)+",import.meta.url).href");
    if(/\bimport\.meta\b(?!\.url)/.test(rewritten.replace(/new URL\("[^"]*",import\.meta\.url\)\.href/g,"")))throw Error("Unsupported import.meta use in "+file);
    return {code:rewritten,map:null};
   }}],
 });
 // codeSplitting:false still keeps one dynamically imported module (bootstrap/candidate-copy8) as its own
 // chunk; that chunk is written next to the entry with a unique "backend-" name.
 let files;
 try{files=(await bundle.write({dir:temporary,format:"esm",codeSplitting:false,sourcemap:false,entryFileNames:path.basename(entry),chunkFileNames:"backend-[name]-[hash].js",banner:"// SHOP_POS_BACKEND_BUNDLE_V1 generated by desktop/bundle-backend.mjs from "+BUNDLED_ENTRY+" and its reviewed runtime dependencies."})).output.map(o=>o.fileName);}
 finally{await bundle.close();}
 try{
  // Only externals or this bundle's own chunks may still be imported, never an original relative module.
  let bytes=0;
  for(const name of files){
   if(name.includes("/")||name.includes("\\")||(name!==path.basename(entry)&&(!name.startsWith("backend-")||existsSync(path.join(outDir,name)))))throw Error("Unexpected bundle output: "+name);
   const text=readFileSync(path.join(temporary,name),"utf8");bytes+=Buffer.byteLength(text);
   const stray=[...text.matchAll(/(?:\bfrom\s*|\bimport\s*\(?\s*)["'](\.{1,2}\/[^"']+)["']/g)].map(m=>m[1]).filter(s=>!files.includes(s.replace(/^\.\//,"")));
   if(stray.length)throw Error("Bundle still imports original relative files: "+stray.slice(0,5).join(", "));
  }
  for(const name of files)renameSync(path.join(temporary,name),path.join(outDir,name));
  const report={format:"SHOP_POS_BACKEND_BUNDLE_V1",entry:BUNDLED_ENTRY,files,bundledModules:bundled.size,bytes,productionActivation:false};
  writeFileSync(path.join(payload,"backend-bundle.json"),JSON.stringify({...report,modules:[...bundled].sort()},null,1));
  return report;
 }finally{rmSync(temporary,{recursive:true,force:true});}
}

if(process.argv[1]&&path.resolve(process.argv[1])===fileURLToPath(import.meta.url))console.log(JSON.stringify(await bundleBackend(process.argv[2])));
