import { expect, test } from "@playwright/test";
import { aggregateMockSales, formatMockRevenue, mockSales } from "../../src/lib/admin/mock-sales";
import { expectReadableContrast } from "./support/contrast";

for (const theme of ["light", "dark"] as const) {
  test("Sales Report periods, original sale disclosure and exact totals in " + theme, async ({ page, baseURL }, testInfo) => {
    const unexpected: string[] = [];
    const errors: string[] = [];
    page.on("pageerror", (error) => errors.push(error.message));
    await page.route("**/*", (route) => {
      const request = route.request();
      if (new URL(request.url()).origin === baseURL && ["GET", "HEAD"].includes(request.method())) return route.continue();
      unexpected.push(request.method() + " " + request.url());
      return route.abort();
    });
    await page.emulateMedia({ colorScheme: theme });
    await page.addInitScript((mode) => localStorage.setItem("pos-theme", mode), theme);
    await page.setViewportSize({ width: 1440, height: 900 });
    await page.goto("/admin/dashboard");
    const card = page.getByRole("group", { name: "Today's Sales Revenue (PKR)", exact: true });
    const link = card.getByRole("link", { name: "Today's Sales Revenue (PKR)", exact: true });
    await expect(card.locator("data")).toHaveAttribute("value", "25690.00");
    for (let step = 0; step < 24; step++) {
      await page.keyboard.press("Tab");
      if (await link.evaluate((element) => element === document.activeElement)) break;
    }
    await expect(link).toBeFocused();
    await expect(link).toHaveCSS("outline-width", "3px");
    await page.keyboard.press("Enter");
    await expect(page).toHaveURL("/admin/sales/today");
    await expect(page).toHaveTitle("Sales Report | Shop POS");
    await expect(page.getByRole("heading", { name: "Sales Report", level: 1 })).toBeVisible();
    await expect(page.getByText("Demo Data", { exact: true })).toBeVisible();
    await expect(page.getByText(/Fixed demo Today:/)).toContainText("2 November 2026 (Asia/Karachi). Fixed examples, not live sales.");
    await expect(page.locator("html")).toHaveAttribute("data-theme", theme);
    await expect(page.getByRole("link", { name: "All previews", exact: true })).toHaveCount(0);
    const sidebar = page.getByRole("complementary", { name: "Admin sidebar" });
    await expect(sidebar.getByRole("button", { name: "Sales", exact: true })).toHaveAttribute("aria-expanded", "true");
    await expect(sidebar.getByRole("button", { name: "Sales", exact: true })).toHaveClass(/bg-muted/);
    await expect(sidebar.getByRole("link", { name: "Sales Report", exact: true })).toHaveAttribute("aria-current", "page");
    const totals = page.getByLabel("Revenue totals", { exact: true });
    const overall = totals.locator("div").filter({ has: page.getByText("Total Sales Revenue", { exact: true }) }).locator("data");
    const selected = totals.locator("div").filter({ has: page.getByText("Selected Products Revenue", { exact: true }) }).locator("data");
    const table = page.getByRole("table", { name: "Mock product-wise sales revenue", exact: true });
    const period = page.getByRole("combobox", { name: "Reporting period", exact: true });
    const search = page.getByRole("searchbox", { name: "Search by product name" });
    const clear = page.getByRole("button", { name: "Clear search", exact: true });
    const back = page.getByRole("link", { name: "Back to Dashboard", exact: true });
    await expect(page.getByRole("region", { name: "Product-wise revenue", exact: true }).getByRole("combobox")).toHaveCount(1);
    await expect(overall).toHaveText("Rs. 25,690.00");
    await expect(selected).toHaveText("Rs. 25,690.00");
    await expect(page.getByText("All products", { exact: true })).toBeVisible();
    const products = aggregateMockSales(mockSales);
    await expect(table.getByRole("rowheader")).toHaveText(products.map((product) => product.productName));
    await expect(table.getByRole("columnheader")).toHaveText(["Product Name", "Quantity Sold", "Total Revenue (PKR)", "Sale details"]);
    for (const product of products) {
      const row = table.getByRole("row").filter({ has: page.getByRole("rowheader", { name: product.productName, exact: true }) });
      await expect(row.getByRole("cell").nth(0)).toHaveText(String(product.quantity));
      await expect(row.getByRole("cell").nth(1)).toHaveText(formatMockRevenue(product.revenuePaise));
    }
    await back.focus();
    await page.keyboard.press("Tab");
    await expect(period).toBeFocused();
    await expect(period).toHaveCSS("outline-width", "3px");
    await page.keyboard.press("Tab");
    await expect(search).toBeFocused();
    await page.keyboard.type("  MILK  ");
    await expect(table.getByRole("rowheader")).toHaveText(["Milk Powder"]);
    await expect(selected).toHaveText("Rs. 6,001.00");
    await expect(overall).toHaveText("Rs. 25,690.00");
    await page.keyboard.press("Tab");
    await expect(clear).toBeFocused();
    await page.keyboard.press("Enter");
    await expect(search).toBeFocused();
    await expect(table.getByRole("rowheader")).toHaveCount(6);

    const diapers = table.getByRole("row").filter({ has: page.getByRole("rowheader", { name: "Diapers", exact: true }) });
    const disclosure = diapers.getByRole("button");
    await disclosure.focus();
    await expect(disclosure).toHaveCSS("outline-width", "3px");
    await page.keyboard.press("Enter");
    await expect(disclosure).toHaveAttribute("aria-expanded", "true");
    const details = page.getByRole("region", { name: "Individual sales for Diapers", exact: true });
    const detailTable = details.getByRole("table", { name: "Original mock sales for Diapers", exact: true });
    await expect(detailTable.getByRole("rowheader")).toHaveText(["demo-sale-1", "demo-sale-2"]);
    await expect(detailTable.getByRole("row").nth(1).getByRole("cell")).toHaveText(["2026-11-02", "2", "Rs. 1,250.25", "Rs. 2,500.50"]);
    await expect(detailTable.getByRole("row").nth(2).getByRole("cell")).toHaveText(["2026-11-02", "4", "Rs. 1,249.75", "Rs. 4,999.00"]);
    await expect(details.getByRole("button", { name: "Close sales", exact: true })).toHaveCount(0);
    await expect(diapers.getByRole("button")).toHaveCount(1);
    await disclosure.focus();
    await page.keyboard.press("Enter");
    await expect(disclosure).toBeFocused();
    await expect(disclosure).toHaveAttribute("aria-expanded", "false");

    await period.selectOption("monthly");
    const month = page.getByLabel("Month and year", { exact: true });
    await expect(month).toHaveValue("2026-11");
    await expect(page.getByText("Selected month: November 2026", { exact: true })).toBeVisible();
    await expect(overall).toHaveText("Rs. 25,690.00");
    await month.fill("2026-10");
    await expect(page.getByText("Selected month: October 2026", { exact: true })).toBeVisible();
    await expect(overall).toHaveText("Rs. 0.00");
    await expect(selected).toHaveText("Rs. 0.00");
    await expect(page.getByText("No sales found for this period.", { exact: true })).toBeVisible();
    await expect(table).toHaveCount(0);
    await period.selectOption("custom");
    const from = page.getByLabel("From Date", { exact: true });
    const to = page.getByLabel("To Date", { exact: true });
    await expect(month).toHaveCount(0);
    await expect(from).toHaveAttribute("type", "date");
    await expect(to).toHaveAttribute("type", "date");
    await expect(page.getByText("From: 02 Nov 2026", { exact: true })).toBeVisible();
    await expect(page.getByText("To: 02 Nov 2026", { exact: true })).toBeVisible();
    await expect(overall).toHaveText("Rs. 25,690.00");
    await from.fill("2026-11-03");
    await expect(page.getByRole("region", { name: "Product-wise revenue", exact: true }).getByRole("alert")).toHaveText("From Date must be on or before To Date.");
    await expect(from).toHaveAttribute("aria-invalid", "true");
    await expect(totals.locator("dd")).toContainText(["—", "—"]);
    await expect(totals.locator("data")).toHaveCount(0);
    await expect(totals.getByText("Rs. 0.00", { exact: true })).toHaveCount(0);
    await expect(table).toHaveCount(0);
    await expect(page.getByText("From: 03 Nov 2026", { exact: true })).toBeVisible();
    await to.fill("2026-11-04");
    await expect(page.getByRole("region", { name: "Product-wise revenue", exact: true }).getByRole("alert")).toHaveCount(0);
    await expect(overall).toHaveText("Rs. 0.00");
    await expect(selected).toHaveText("Rs. 0.00");
    await expect(page.getByText("No sales found for this period.", { exact: true })).toBeVisible();
    await from.fill("2026-11-01");
    await to.fill("2026-11-02");
    await expect(overall).toHaveText("Rs. 25,690.00");
    await search.fill("DIAP");
    await expect(selected).toHaveText("Rs. 7,499.50");
    await expect(overall).toHaveText("Rs. 25,690.00");
    await disclosure.click();
    await expect(detailTable.getByRole("rowheader")).toHaveCount(2);
    await to.fill("2026-11-01");
    await expect(overall).toHaveText("Rs. 0.00");
    await expect(details).toHaveCount(0);
    await from.fill("2026-11-02");
    await to.fill("2026-11-02");
    await expect(overall).toHaveText("Rs. 25,690.00");
    await expect(selected).toHaveText("Rs. 7,499.50");
    await clear.click();
    await expect(page.getByText("From: 02 Nov 2026", { exact: true })).toBeVisible();
    await expect(page.getByText("To: 02 Nov 2026", { exact: true })).toBeVisible();
    await expect(table.getByRole("rowheader")).toHaveCount(6);
    await disclosure.click();
    await expect(page.locator("[data-connectivity-state]")).toHaveAttribute("data-connectivity-state", "connected");
    await expectReadableContrast(page);
    if (theme === "dark" && testInfo.project.name === "chromium") {
      await page.screenshot({ path: testInfo.outputPath("sales-report-desktop.png"), fullPage: true, scale: "css" });
    }
    for (const width of [1024, 768, 375, 320]) {
      await page.setViewportSize({ width, height: 900 });
      await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth - window.innerWidth), { message: "No horizontal overflow at " + width + "px" }).toBeLessThanOrEqual(0);
      await expect(search).toBeVisible();
      await expect(period).toBeVisible();
      await expect(clear).toBeVisible();
      await expect(back).toBeVisible();
      await expect(details).toBeVisible();
    }
    await period.selectOption("today");
    await expect(from).toHaveCount(0);
    await expect(overall).toHaveText("Rs. 25,690.00");
    await back.focus();
    await page.keyboard.press("Enter");
    await expect(page).toHaveURL("/admin/dashboard");
    await card.click({ position: { x: 20, y: 20 } });
    await expect(page).toHaveURL("/admin/sales/today");
    expect(unexpected).toEqual([]);
    expect(errors).toEqual([]);
  });
}

test("Sales Report direct route preserves System theme", async ({ page }) => {
  await page.emulateMedia({ colorScheme: "light" });
  await page.goto("/admin/sales/today");
  await page.getByLabel("Theme", { exact: true }).selectOption("system");
  await expect(page.locator("html")).toHaveAttribute("data-theme", "light");
  await page.emulateMedia({ colorScheme: "dark" });
  await expect(page.locator("html")).toHaveAttribute("data-theme", "dark");
  await page.reload();
  await expect(page.getByLabel("Theme", { exact: true })).toHaveValue("system");
  await expect(page.locator("html")).toHaveAttribute("data-theme", "dark");
  await expect(page.getByRole("table", { name: "Mock product-wise sales revenue" }).getByRole("rowheader")).toHaveCount(6);
});

test("Sales submenu supports keyboard navigation and mobile drawer focus", async ({ page }) => {
  await page.setViewportSize({ width: 1280, height: 900 });
  await page.goto("/admin/dashboard");
  const navigation = page.getByRole("navigation", { name: "Main navigation", exact: true });
  const sales = navigation.getByRole("button", { name: "Sales", exact: true });
  const report = navigation.getByRole("link", { name: "Sales Report", exact: true });
  await expect(sales).toHaveAttribute("aria-expanded", "false");
  await sales.focus();
  await expect(sales).toHaveCSS("outline-width", "3px");
  await page.keyboard.press("Enter");
  await expect(sales).toHaveAttribute("aria-expanded", "true");
  await expect(navigation.getByRole("list", { name: "Sales pages", exact: true }).getByRole("link")).toHaveCount(1);
  await page.keyboard.press("Tab");
  await expect(report).toBeFocused();
  await page.keyboard.press("Enter");
  await expect(page).toHaveURL("/admin/sales/today");
  await expect(sales).toHaveAttribute("aria-expanded", "true");
  await expect(report).toHaveAttribute("aria-current", "page");
  await sales.press("Space");
  await expect(report).toBeHidden();
  await sales.press("Enter");
  await expect(report).toBeVisible();
  await navigation.getByRole("link", { name: "Products", exact: true }).click();
  await expect(page).toHaveURL("/admin/products");
  await expect(sales).toHaveAttribute("aria-expanded", "false");
  await page.setViewportSize({ width: 375, height: 900 });
  const opener = page.getByRole("button", { name: "Open navigation", exact: true });
  await opener.click();
  const drawer = page.getByRole("dialog", { name: "Admin navigation", exact: true });
  const mobile = drawer.getByRole("navigation", { name: "Mobile navigation", exact: true });
  const mobileSales = mobile.getByRole("button", { name: "Sales", exact: true });
  await mobileSales.focus();
  await mobileSales.press("Space");
  await page.keyboard.press("Tab");
  await expect(mobile.getByRole("link", { name: "Sales Report", exact: true })).toBeFocused();
  await page.keyboard.press("Enter");
  await expect(page).toHaveURL("/admin/sales/today");
  await expect(drawer).toBeHidden();
  await opener.click();
  await expect(mobileSales).toHaveAttribute("aria-expanded", "true");
  await expect(mobile.getByRole("link", { name: "Sales Report", exact: true })).toHaveAttribute("aria-current", "page");
  await page.keyboard.press("Escape");
  await expect(drawer).toBeHidden();
  await expect(opener).toBeFocused();
});
